"""
模块 15 · 内容边界检查（温柔拒绝）
--------------------------------------------------------------------
作用：拦截「游戏娱乐」「代刷作弊」这类与学习无关或违规的请求，
      给出一句温和的拒绝，并把话题引回学习，避免大模型顺着聊下去。
"""

from __future__ import annotations

# 12b.1 娱乐/游戏关键词
GAME_WORDS = (
    "游戏", "打游戏", "王者荣耀", "原神", "英雄联盟", "lol", "steam", "吃鸡", "和平精英",
    "第五人格", "蛋仔", "抽卡", "手游", "电竞", "代打", "开黑", "上分", "皮肤", "氪金",
)

# 12b.2 违规作弊关键词
CHEAT_WORDS = ("代刷", "代考", "代写", "外挂", "作弊", "刷课", "代练", "破解", "论文代写")

GAME_REPLY = (
    "这个问题我就不帮你查啦～ 游戏和学习无关，我更愿意陪你把功课弄明白。\n"
    "要不要看看你今天的课表，或者我帮你查查最近的考试安排呀？"
)

CHEAT_REPLY = (
    "这个我不能帮你做哦，代刷、代考这类事情违反校规，严重会影响学籍。\n"
    "如果课程跟不上，我可以帮你找出薄弱科目、给学习建议，也可以告诉你补考怎么安排～"
)


def check(text: str) -> str | None:
    """命中违规则返回拒绝文案，否则返回 None。"""
    content = (text or "").lower()
    if any(w in content for w in CHEAT_WORDS):
        return CHEAT_REPLY
    if any(w in content for w in GAME_WORDS):
        return GAME_REPLY
    return None
